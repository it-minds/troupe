defmodule Mix.Tasks.Troupe.Theme do
  @shortdoc "Generate the brand stylesheet from a theme kit's tokens"

  @moduledoc """
  Turn one of `clients/gui/docs/design/themes/*.tokens.json` into
  `apps/troupe_plane/priv/static/theme.css`.

      mix troupe.theme
      mix troupe.theme --theme limelight
      mix troupe.theme --check

  ## What this is, and what it is not

  `clients/gui/docs/design/themes/THEMES.md` describes four themes over one token
  contract — Afterglow, the design, and Footlight, Limelight and Signal on its structure
  — of which **Signal** is the one the front page wears: neutral graphite with no blue
  cast, cyan for the machine working and magenta, the reserved colour, for a person
  being asked to decide and nothing else. Afterglow spends its pink on links and the
  accent too (root Decision 702), which the front page's rule — the reserved colour on
  the mask and the approval figure alone — does not allow. This task writes the theme
  out as the stylesheet the plane's front page loads.

  The themes are one set of files, the GUI's, which `pnpm tokens` and the TUI's
  `mix troupe.palette` read as well (Decision 716); a copy here once drifted from them.

  The walk that turns a token document into declarations was written for the plane's
  own console, whose `docs/design/admin/tokens.json` had the same shape; that console is
  an app of its own now, with the GUI's tokens, and this is the one stylesheet the plane
  still generates.

  ## The naming

  A variable is its path through the document, hyphenated.
  `color.status.waiting.solid` becomes `--color-status-waiting-solid`,
  `typography.role.body` becomes both the five parts and the CSS `font` shorthand. Dark
  values land on `:root`, light under `:root[data-theme="light"]` and the system
  preference — Signal's own `defaultMode` is dark.

  Generated and committed, with `--check` for CI, so the bytes a browser is served
  cannot drift from the kit a designer edits.
  """

  use Mix.Task

  @output_path Path.join(~w(apps troupe_plane priv static theme.css))
  @themes_dir Path.join(~w(clients gui docs design themes))

  # The main theme. Changing this line changes what the front page wears; the other
  # three stay renderable through `--theme`.
  @default_theme "signal"

  @impl Mix.Task
  def run(argv) do
    {opts, _rest, _invalid} =
      OptionParser.parse(argv, strict: [check: :boolean, theme: :string])

    theme = opts[:theme] || @default_theme
    source = Path.join(@themes_dir, "#{theme}.tokens.json")

    css = source |> read!() |> render(source: source, task: task_line(theme))

    if opts[:check], do: check(css), else: write(css)
  end

  defp task_line(@default_theme), do: "mix troupe.theme"
  defp task_line(theme), do: "mix troupe.theme --theme #{theme}"

  defp write(css) do
    File.mkdir_p!(Path.dirname(@output_path))
    File.write!(@output_path, css)
    Mix.shell().info("wrote #{@output_path} (#{byte_size(css)} bytes)")
  end

  defp check(expected) do
    case File.read(@output_path) do
      {:ok, ^expected} ->
        Mix.shell().info("theme.css is current")

      {:ok, _stale} ->
        Mix.raise("#{@output_path} is stale: run `mix troupe.theme` and commit it")

      {:error, _reason} ->
        Mix.raise("#{@output_path} is missing: run `mix troupe.theme`")
    end
  end

  @doc false
  @spec read!(Path.t()) :: map()
  def read!(path) do
    case File.read(path) do
      {:ok, contents} -> Jason.decode!(contents)
      {:error, reason} -> Mix.raise("cannot read #{path}: #{:file.format_error(reason)}")
    end
  end

  @doc """
  The stylesheet for one token document.

  `:source` and `:task` name, in the header comment, where the values came from and what
  regenerates them, so a reader who finds a stale value knows which file to edit and what
  to run. The walk is the one the plane's own console's token document went through
  while that console existed, and it still reads a leaf of any theme kit's shape.
  """
  @spec render(map(), keyword()) :: String.t()
  def render(tokens, opts) do
    source = Keyword.fetch!(opts, :source)
    task = Keyword.fetch!(opts, :task)
    {dark, light, plain} = collect(tokens)
    plain = plain ++ fonts(tokens)

    # Two tokens that generate the same variable is a value silently lost, which is how
    # `color.border.hairline` and `border.hairline` were one variable for a while.
    for bucket <- [plain ++ dark, light] do
      case bucket |> Enum.frequencies_by(&elem(&1, 0)) |> Enum.filter(&(elem(&1, 1) > 1)) do
        [] -> :ok
        clashes -> raise "tokens collide: #{inspect(Enum.map(clashes, &elem(&1, 0)))}"
      end
    end

    """
    /* Generated by `#{task}` from #{source}.
       Do not edit: change the tokens and regenerate. */

    :root {
    #{declarations(plain ++ dark)}
    }

    /* An explicit light choice, and the system preference where no choice was made.
       Written twice rather than once so that `data-theme="dark"` beats a light OS. */
    :root[data-theme="light"] {
    #{declarations(light)}
    }

    @media (prefers-color-scheme: light) {
      :root:not([data-theme="dark"]) {
    #{declarations(light, "    ")}
      }
    }
    """
  end

  # The design's type table is role to font, and CSS has a shorthand for exactly that.
  # Composed here rather than left to the stylesheet so a role is one token, and so five
  # parts cannot be recombined differently on two different pages.
  defp fonts(tokens) do
    families = get_in(tokens, ["typography", "family"]) || %{}

    tokens
    |> get_in(["typography", "role"])
    |> Kernel.||(%{})
    |> Enum.reject(fn {key, _value} -> meta?(key) end)
    |> Enum.sort()
    |> Enum.map(fn {role, spec} ->
      family = unwrap(Map.get(families, spec["family"], spec["family"]))
      weight = unwrap(spec["weight"])
      size = unwrap(spec["size"])
      height = unwrap(spec["lineHeight"])
      {var(["typography", "role", role]), "#{weight} #{size}/#{height} #{family}"}
    end)
  end

  # A token is sometimes the value and sometimes `{value, description}`; both shapes
  # appear in the document and both mean the same thing to a stylesheet.
  defp unwrap(%{"value" => value}), do: value
  defp unwrap(value), do: value

  defp declarations(pairs, indent \\ "  ") do
    Enum.map_join(pairs, "\n", fn {name, value} -> "#{indent}#{name}: #{value};" end)
  end

  # Walks the document once, sorting every leaf into three buckets: the dark half of a
  # themed value, the light half, and everything that is the same in both.
  defp collect(tokens) do
    tokens
    |> Enum.reject(fn {key, _value} -> meta?(key) end)
    |> Enum.reduce({[], [], []}, fn {group, value}, acc ->
      walk(value, prefix(group), acc)
    end)
    |> then(fn {dark, light, plain} ->
      {Enum.reverse(dark), Enum.reverse(light), Enum.reverse(plain)}
    end)
  end

  # A map carrying both `dark` and `light` is one themed value, not two nested ones.
  defp walk(%{"dark" => dark, "light" => light}, path, {d, l, p}) do
    {[{var(path), dark} | d], [{var(path), light} | l], p}
  end

  defp walk(%{} = map, path, acc) do
    map
    |> Enum.reject(fn {key, _value} -> meta?(key) end)
    |> Enum.reduce(acc, fn {key, value}, inner -> walk(value, path ++ [key], inner) end)
  end

  defp walk(value, path, {d, l, p} = acc) when is_binary(value) or is_number(value) do
    if annotation?(path), do: acc, else: {d, l, [{var(path), quoted(path, value)} | p]}
  end

  # Lists are documentation — a theme list, a set of rules — and describe the system
  # rather than being a value any rule can use.
  defp walk(_other, _path, acc), do: acc

  # `$meta`, `$note`, `$shape`: prose about the system, addressed to a reader.
  defp meta?(key), do: String.starts_with?(key, "$")

  # Descriptions and measured contrast ratios document a token for a reader; they are
  # prose about the system rather than anything a rule can use, so a leaf whose last
  # segment is one of these is dropped rather than emitted as a value.
  @annotations ~w(description contrastOnPanel contrastOnCanvas note use)

  defp annotation?(path), do: List.last(path) in @annotations

  # A glyph and a status word are values a rule genuinely uses — `content: var(--…)` for
  # the glyph — and both can contain a space or a character CSS would not accept bare.
  @quoted ~w(glyph word)

  defp quoted(path, value) do
    if List.last(path) in @quoted, do: ~s("#{value}"), else: value
  end

  # No group is dropped. `color.border.hairline` is a colour and `border.hairline` is a
  # width; dropping the `color.` prefix made them one variable, and whichever the walk
  # reached last silently won.
  defp prefix(group), do: [group]

  defp var(path) do
    path
    |> trim_value()
    |> Enum.map_join("-", &hyphenate/1)
    |> then(&("--" <> &1))
  end

  # `breakpoint.lg.value` is the breakpoint; the segment carries no meaning of its own.
  defp trim_value(path) do
    case Enum.reverse(path) do
      ["value" | rest] when rest != [] -> Enum.reverse(rest)
      _other -> path
    end
  end

  # `rowHeight` becomes `row-height`, so a name in CSS reads the way CSS names read.
  defp hyphenate(segment) do
    segment
    |> String.replace(~r/([a-z0-9])([A-Z])/, "\\1-\\2")
    |> String.downcase()
  end
end
