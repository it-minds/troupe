defmodule Mix.Tasks.Troupe.Openbao.Policy do
  @shortdoc "Generate the page that says what OpenBao must grant the plane"

  @moduledoc """
  Write `docs/admin/openbao.md` from `Troupe.KMS.Policy.plane_grants/1`, and the kind
  cluster's `dev/kind/openbao-plane.yaml` from the same list.

      mix troupe.openbao.policy
      mix troupe.openbao.policy --check

  ## Why generated

  The plane checks each of these grants against its own token when it starts and on the
  console's Overview, and prints the lines for one it lacks. The page an administrator
  reads before installing says the same, because it is written from the same list: a
  grant added to the code is on the page, and a page that asked for less than the plane
  checks for is a test failure rather than a 403 at the first signed answer.

  The kind cluster's plane logs in under a role made from the same list, with those
  policies and nothing more, so the cluster suite meets the check against the role a
  deployment gives the plane rather than against a root token, which holds everything.

  `--check` the same shape as `mix troupe.egress --check`: the committed bytes cannot drift
  from what they are generated from. A test (`Troupe.KMS.PolicyTest`) runs it too.
  """

  use Mix.Task

  alias Troupe.KMS.Policy

  @output Path.join(~w(docs admin openbao.md))
  @kind_output Path.join(~w(dev kind openbao-plane.yaml))

  @impl Mix.Task
  def run(argv) do
    {opts, _rest, _invalid} = OptionParser.parse(argv, strict: [check: :boolean])

    for {path, document} <- [{@output, render()}, {@kind_output, render_kind()}] do
      if opts[:check] do
        check(path, document)
      else
        File.mkdir_p!(Path.dirname(path))
        File.write!(path, document)
        Mix.shell().info("wrote #{path} (#{length(Policy.plane_grants())} grants)")
      end
    end
  end

  @doc "Where the page is, from the repository's root."
  @spec output() :: Path.t()
  def output, do: @output

  @doc "Where the kind cluster's policies are, from the repository's root."
  @spec kind_output() :: Path.t()
  def kind_output, do: @kind_output

  defp check(path, document) do
    case File.read(path) do
      {:ok, ^document} ->
        Mix.shell().info("#{path} is current")

      {:ok, _stale} ->
        Mix.raise("""
        #{path} does not match `Troupe.KMS.Policy.plane_grants/1`.

        Run `mix troupe.openbao.policy` and commit the result. The page is generated so that
        it asks for exactly what the plane checks for.
        """)

      {:error, _reason} ->
        Mix.raise("#{path} is missing: run `mix troupe.openbao.policy`")
    end
  end

  @doc """
  The kind cluster's plane policies, as `dev/kind/openbao-plane.yaml` holds them: a
  ConfigMap the OpenBao setup Job in `dev/kind/dependencies.yaml` mounts, with each policy
  as `<name>.hcl` and the line that makes the plane's role carry all of them, the GitHub
  App's included, since the cluster suite sets an App up.
  """
  @spec render_kind() :: String.t()
  def render_kind do
    grants = Policy.plane_grants()
    role = Policy.plane_role_line(policies: Enum.map(grants, & &1.policy))

    policies =
      Enum.map_join(grants, "", fn grant ->
        "  #{grant.policy}.hcl: |\n" <> indent(Policy.grant_policy(grant), "    ")
      end)

    """
    # Generated by `mix troupe.openbao.policy` from `Troupe.KMS.Policy.plane_grants/1`.
    # Do not edit: docs/admin/openbao.md is written from the same list.
    #
    # The kind cluster's plane logs in as its ServiceAccount under the role `troupe-plane`,
    # carrying these policies and no other, as a deployment's does: the OpenBao setup Job in
    # dependencies.yaml writes each policy and runs `role`. So the plane's check of its
    # grants meets a role that holds what the docs say and nothing more.
    apiVersion: v1
    kind: ConfigMap
    metadata:
      name: openbao-plane-policies
      namespace: troupe-system
    data:
      role: |
        #{role}
    """ <> policies
  end

  defp indent(text, prefix) do
    text
    |> String.split("\n")
    |> Enum.map_join("\n", fn
      "" -> ""
      line -> prefix <> line
    end)
  end

  @doc "The page, as `docs/admin/openbao.md` holds it."
  @spec render() :: String.t()
  def render do
    grants = Policy.plane_grants()

    """
    # What OpenBao must grant

    <!-- Generated by `mix troupe.openbao.policy` from `Troupe.KMS.Policy.plane_grants/1`.
         Do not edit: the plane checks the same list against its own token. -->

    The plane cannot write its own policies. That takes an OpenBao administrator, a root
    token or one allowed to write `sys/policies/acl` and the auth roles, which the plane
    never is. So an administrator runs the lines below once, and again for a grant an
    upgrade adds; nothing else here is done by hand.

    **The plane checks them.** When it starts, and on the console's Overview, the plane asks
    OpenBao what its own token may do at each path below, look-only
    (`sys/capabilities-self`, which the `default` policy allows), and says in one sentence
    for each grant it lacks what fails without it, with the lines that grant it, written
    with the deployment's own mounts, key names, role and the policies its token already
    carries. `admin.overview` answers the same as `openbao`.

    The names are the defaults: mounts `secret` (KV v2) and `transit`, the Kubernetes auth
    mount `kubernetes`, the role `troupe-plane` (the chart's `bao.authPath` and
    `bao.planeRole`), and the release namespace `troupe-system`.

    ## 1. Before the plane starts

    The engines, the session-token key, Kubernetes auth with a reviewer
    ([integrations.md §2](integrations.md#2-openbao)), and the plane's role, carrying the
    policy of every grant the plane needs:

    ```sh
    bao secrets enable -path=transit transit
    bao secrets enable -path=secret -version=2 kv
    bao write -f transit/keys/troupe-session-tokens type=ecdsa-p256
    bao auth enable kubernetes
    bao write auth/kubernetes/config kubernetes_host=https://kubernetes.default.svc:443   # and the reviewer's JWT and CA
    #{Policy.plane_role_line()}
    ```

    Then write each policy in section 2. A plane whose role is missing or refuses its
    ServiceAccount token says so at start, and on the Overview, with the role line above.

    ## 2. What the plane's role carries

    | grant | policy | what it is for | without it |
    | --- | --- | --- | --- |
    #{Enum.map_join(grants, "\n", &row/1)}

    #{Enum.map_join(grants, "\n", &section/1)}
    ## 3. Workers and people

    Their roles are not the plane's, and the plane cannot check them: a worker pod logs in
    as `troupe-worker` (or a role per profile), and a person's daemon at the `jwt` auth mount
    as `#{Policy.person_policy_name()}`. Their policies and roles are in
    [roles-and-permissions.md §8](roles-and-permissions.md#8-openbao-policies), rendered by
    the same module.
    """
  end

  defp row(grant) do
    name =
      if grant.required,
        do: "`#{grant.id}`",
        else: "`#{grant.id}` (#{grant[:only] || "only with a GitHub App"})"

    "| #{name} | `#{grant.policy}` | #{grant.for} | #{grant.without} |"
  end

  defp only_where(%{required: true}), do: ""
  defp only_where(%{id: "invites"}), do: " Only where people are invited into private sessions."
  defp only_where(_grant), do: " Only where the plane has a GitHub App."

  defp section(grant) do
    """
    ### `#{grant.policy}`

    To #{grant.for}.#{only_where(grant)}

    ```sh
    #{String.trim_trailing(Policy.grant_lines(grant, role: "troupe-plane", policies: plane_policies(grant)))}
    ```
    """
  end

  # The role as section 1 makes it, so adding a grant to it keeps the others.
  defp plane_policies(_grant) do
    for grant <- Policy.plane_grants(), grant.required, do: grant.policy
  end
end
