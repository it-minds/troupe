// Generate `packages/client/src/lines.ts` and `clients/gui/docs/design/lines.order.json` from
// `docs/design/lines.json`, the status lines of every loading and starting state.
//
//   pnpm lines
//   pnpm lines:check
//
// The design file is the source of truth for the words, as the theme files are for the
// colours: the terminal client's reader is generated from the same file by
// `mix troupe.lines`, and the two are held to one picking rule by the order fixture
// written here, which both test suites read. Copying a line into a component by hand is
// how the two clients stop saying the same things. `--check` fails if a generated file
// is not what the sources say, which is what CI runs.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { LINE_SEEDS, orderOf } from "./lines-rule.js";

const root = fileURLToPath(new URL("../", import.meta.url));
const source = fileURLToPath(new URL("../../../docs/design/lines.json", import.meta.url));
const reader = `${root}packages/client/src/lines.ts`;
const fixture = `${root}docs/design/lines.order.json`;

type Kinds = Record<string, string[]>;

function read(): Kinds {
  const file = JSON.parse(readFileSync(source, "utf8")) as { kinds?: Kinds };
  const kinds = file.kinds;
  if (!kinds || typeof kinds !== "object") throw new Error("docs/design/lines.json has no `kinds`");
  for (const [kind, lines] of Object.entries(kinds)) {
    if (!/^[a-z][a-z_]*$/.test(kind)) throw new Error(`lines.json: \`${kind}\` is not a lower-case name`);
    if (!Array.isArray(lines) || lines.length === 0) throw new Error(`lines.json: \`${kind}\` has no lines`);
    const seen = new Set<string>();
    for (const line of lines) {
      if (typeof line !== "string" || line.trim() === "" || line !== line.trim()) throw new Error(`lines.json: ${kind}: \`${line}\` is not a trimmed string`);
      if (/[!]/u.test(line) || /\p{Extended_Pictographic}/u.test(line)) throw new Error(`lines.json: ${kind}: \`${line}\` has an exclamation mark or an emoji`);
      if (seen.has(line)) throw new Error(`lines.json: ${kind}: \`${line}\` is there twice`);
      seen.add(line);
    }
  }
  return kinds;
}

const rule = readFileSync(fileURLToPath(new URL("./lines-rule.ts", import.meta.url)), "utf8");
// The rule's own text goes into the reader, from its marker to its end, so the two cannot differ.
const body = rule.slice(rule.indexOf("// -- the picking rule"));

function render(kinds: Kinds): string {
  const entries = Object.entries(kinds)
    .map(([kind, lines]) => `  ${kind}: [\n${lines.map((l) => `    ${JSON.stringify(l)},`).join("\n")}\n  ],`)
    .join("\n");
  return `// Generated by \`pnpm lines\` from docs/design/lines.json. Do not edit it; edit the file and run
// the script. \`pnpm lines:check\` (CI) fails when this is not what the file says.
//
// The status lines of every loading and starting state, by what each is said over, and the
// rule that picks one (docs/design/frames.md section 7).

export const LINES = {
${entries}
} as const;

export type LineKind = keyof typeof LINES;

${body}
/** The order a kind's lines are taken in for a seed: indices into \`LINES[kind]\`. */
export function order(kind: LineKind, seed: string): number[] {
  return orderOf(kind, seed, LINES[kind].length);
}

/** The n-th line (from 1) taken for a seed, or null past the end of the list: the facts alone. */
export function pick(kind: LineKind, seed: string, n: number): string | null {
  const i = order(kind, seed)[n - 1];
  return i === undefined ? null : (LINES[kind][i] ?? null);
}

/** The first line taken for a seed: for a surface that says one line and no more. */
export function first(kind: LineKind, seed: string): string {
  return pick(kind, seed, 1) ?? LINES[kind][0];
}
`;
}

function fixtureOf(kinds: Kinds): string {
  const out: Record<string, Record<string, number[]>> = {};
  for (const seed of LINE_SEEDS) {
    out[seed] = {};
    for (const [kind, lines] of Object.entries(kinds)) out[seed]![kind] = orderOf(kind, seed, lines.length);
  }
  return `${JSON.stringify({ about: "Generated by pnpm lines. For each seed, the order each kind's lines are taken in; the TUI's and the desktop's readers must both give it.", seeds: out }, null, 2)}\n`;
}

const kinds = read();
const files: Array<[string, string]> = [
  [reader, render(kinds)],
  [fixture, fixtureOf(kinds)],
];

if (process.argv.includes("--check")) {
  const stale = files.filter(([path, text]) => {
    try {
      return readFileSync(path, "utf8") !== text;
    } catch {
      return true;
    }
  });
  if (stale.length > 0) {
    console.error(`stale: ${stale.map(([p]) => p).join(", ")}\nrun \`pnpm lines\` and commit the result`);
    process.exit(1);
  }
  console.log("the status lines are what docs/design/lines.json says");
} else {
  for (const [path, text] of files) writeFileSync(path, text);
  console.log(`wrote ${files.length} files from ${Object.keys(kinds).length} kinds`);
}
