defmodule Mix.Tasks.Troupe.Lines do
  @moduledoc """
  Generate `lib/troupe/ui/lines.ex` from `docs/design/lines.json`, the status lines of
  every loading and starting state.

      mix troupe.lines
      mix troupe.lines --check

  The words are one file for the terminal client, the desktop app and the console, since
  a line typed into one of them by hand is how they stop saying the same things: the
  desktop's and the console's reader is `packages/client/src/lines.ts`, written by
  `pnpm lines` in `clients/gui`, and this writes the terminal's. `--check` (in `mix
  check`, which CI runs) fails when the module is not what the file says.

  ## What it writes

  Every kind of line by name, in the file's order, and the picking rule: the order a
  kind's lines are taken in for a seed. The rule is the one `scripts/lines-rule.ts`
  writes in TypeScript, an FNV-1a hash of `kind/seed` into a mulberry32 stream that drives
  a Fisher-Yates shuffle, all on unsigned 32 bits. `clients/gui/docs/design/lines.order.json`, which
  `pnpm lines` writes from the TypeScript reader, is what the tests of both hold to it.
  """

  use Mix.Task

  @shortdoc "Generate the TUI's status lines from docs/design/lines.json"

  @source Path.join(~w(.. .. docs design lines.json))
  @output Path.join(~w(lib troupe ui lines.ex))

  @impl Mix.Task
  def run(argv) do
    {opts, _rest, _invalid} = OptionParser.parse(argv, strict: [check: :boolean])
    source = render(read!())
    if opts[:check], do: check(source), else: write(source)
  end

  defp read! do
    kinds = @source |> File.read!() |> Jason.decode!() |> Map.fetch!("kinds")

    for {kind, lines} <- kinds do
      unless kind =~ ~r/^[a-z][a-z_]*$/, do: Mix.raise("lines.json: `#{kind}` is not a name")
      unless is_list(lines) and lines != [], do: Mix.raise("lines.json: `#{kind}` has no lines")

      for line <- lines do
        if line != String.trim(line) or line == "" or String.contains?(line, "!") or
             Enum.uniq(lines) != lines,
           do: Mix.raise("lines.json: #{kind}: `#{line}` is not a plain, trimmed, single line")
      end
    end

    # The file's own order, which a decoded map does not keep.
    order = Regex.scan(~r/^    "([a-z_]+)": \[/m, File.read!(@source), capture: :all_but_first)

    Enum.map(order, fn [kind] -> {kind, Map.fetch!(kinds, kind)} end)
  end

  defp render(kinds) do
    entries =
      Enum.map_join(kinds, ",\n", fn {kind, lines} ->
        "      #{kind}: [\n#{Enum.map_join(lines, ",\n", &("        " <> inspect(&1)))}\n      ]"
      end)

    names = Enum.map_join(kinds, " | ", fn {kind, _} -> ":#{kind}" end)

    """
    # Generated by `mix troupe.lines` from docs/design/lines.json. Do not edit it; edit the
    # file and run the task. `mix troupe.lines --check` fails when this is not what the
    # file says.
    defmodule Troupe.UI.Lines do
      @moduledoc \"\"\"
      The status lines of every loading and starting state, by what each is said over, and
      the rule that picks one (`docs/design/frames.md` section 7). The desktop app and the
      console read the same file through `@troupe/client`.

      Per turn, or per wait, the lines of a kind are taken in an order shuffled from a
      seed, the turn's id, else the session's, else a counter: nothing repeats within a
      turn, two turns do not open the same way, and past the end of the list there is no
      line, which is the facts alone.
      \"\"\"

      import Bitwise

      @lines %{
    #{entries}
      }

      @typedoc "What a line is said over."
      @type kind :: #{names}

      @doc "Every kind, in the file's order."
      @spec kinds() :: [kind()]
      def kinds, do: Map.keys(@lines)

      @doc "A kind's lines, in the file's order."
      @spec all(kind()) :: [String.t()]
      def all(kind), do: Map.fetch!(@lines, kind)

      @doc "The indices of a kind's lines in the order they are taken for a seed."
      @spec order(kind(), term()) :: [non_neg_integer()]
      def order(kind, seed), do: order_of(Atom.to_string(kind), to_string(seed), length(all(kind)))

      @doc "The n-th line (from 1) taken for a seed, or nil past the end of the list: the facts alone."
      @spec pick(kind(), term(), pos_integer()) :: String.t() | nil
      def pick(kind, seed, n) when n >= 1 do
        case Enum.at(order(kind, seed), n - 1) do
          nil -> nil
          index -> Enum.at(all(kind), index)
        end
      end

      @doc "The first line taken for a seed: for a surface that says one line and no more."
      @spec first(kind(), term()) :: String.t()
      def first(kind, seed), do: pick(kind, seed, 1)

      @mask 0xFFFFFFFF

      @doc false
      @spec order_of(String.t(), String.t(), non_neg_integer()) :: [non_neg_integer()]
      def order_of(_kind, _seed, 0), do: []

      def order_of(kind, seed, length) do
        state = fnv1a(kind <> "/" <> seed)
        start = Map.new(0..(length - 1), &{&1, &1})

        {indices, _state} =
          Enum.reduce((length - 1)..1//-1, {start, state}, fn i, {indices, state} ->
            {draw, state} = step(state)
            j = rem(draw, i + 1)
            {indices |> Map.put(i, indices[j]) |> Map.put(j, indices[i]), state}
          end)

        Enum.map(0..(length - 1), &indices[&1])
      end

      defp fnv1a(text) do
        for <<byte <- text>>, reduce: 0x811C9DC5 do
          h -> band(bxor(h, byte) * 0x01000193, @mask)
        end
      end

      # One step of mulberry32: the new state, and the draw.
      defp step(state) do
        a = band(state + 0x6D2B79F5, @mask)
        t = band(bxor(a, a >>> 15) * bor(a, 1), @mask)
        t = bxor(t, band(t + band(bxor(t, t >>> 7) * bor(t, 61), @mask), @mask))
        {bxor(t, t >>> 14), a}
      end
    end
    """
    |> Code.format_string!(line_length: 100)
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  defp write(source) do
    File.write!(@output, source)
    Mix.shell().info("wrote #{@output} (#{byte_size(source)} bytes)")
  end

  defp check(expected) do
    case File.read(@output) do
      {:ok, ^expected} ->
        Mix.shell().info("#{@output} is current")

      {:ok, _stale} ->
        Mix.raise("#{@output} is stale: run `mix troupe.lines` and commit it")

      {:error, _reason} ->
        Mix.raise("#{@output} is missing: run `mix troupe.lines`")
    end
  end
end
